/**
 * Fetch CloudSim projects by year with local fallback.
 */
export const fetchCloudSimProjects = async (academicYear = "2024 - 2025") => {
  try {
    const res = await fetch(`${API_BASE}/project_titles.php?tech=cloud-sim&year=${encodeURIComponent(academicYear)}`);
    if (res.ok) {
      const json = await res.json();
      const items = Array.isArray(json) ? json : json.data || [];
      if (items && items.length > 0) {
        return items.map((item, idx) => ({
          id: item.id || idx + 1,
          title: item.title_name || item.title || `CloudSim Project ${idx + 1}`,
          domain: item.domain || "Cloud Computing & Simulation",
          category: item.category || "Resource Management & VM Allocation",
          tech: item.tech ? (Array.isArray(item.tech) ? item.tech : item.tech.split(",")) : ["Java", "CloudSim", "Eclipse", "CloudAnalyst"],
          description: item.description || "IEEE Standard CloudSim Project implementation with full Java source code, simulation logs, and base paper.",
          abstract: item.abstract || "Comprehensive experimental evaluation and simulation analysis using CloudSim standard benchmarks.",
          year: item.academic_year || academicYear,
          difficulty: item.difficulty || "Advanced",
        }));
      }
    }
  } catch (err) {
    console.warn(`Database API fetch fallback to local data for CloudSim ${academicYear}:`, err);
  }

  if (academicYear.includes("2024") || academicYear.includes("2025")) {
    return cloudSimProjects2024;
  }

  return cloudSimProjectsDataset.map((p) => ({ ...p, year: academicYear }));
};

