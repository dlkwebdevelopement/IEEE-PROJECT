/**
 * Fetch projects by framework with local dataset fallback.
 */
export const fetchFrameworkProjects = async (framework = "django") => {
  const norm = (framework || "django").toLowerCase();
  try {
    const res = await fetch(`${API_BASE}/project_titles.php?tech=${norm}`);
    if (res.ok) {
      const json = await res.json();
      const items = Array.isArray(json) ? json : json.data || [];
      if (items && items.length > 0) {
        return items.map((item, idx) => ({
          id: item.id || idx + 1,
          title: item.title_name || item.title || `${framework} Project ${idx + 1}`,
          domain: item.domain || "Web Application Frameworks",
          category: item.category || "Web Development & AI",
          tech: item.tech ? (Array.isArray(item.tech) ? item.tech : item.tech.split(",")) : ["Python", norm.toUpperCase(), "HTML/CSS", "Database"],
          description: item.description || `IEEE Project implementation using ${norm} framework with complete source code and base paper.`,
          abstract: item.abstract || `Comprehensive architecture and experimental evaluation in ${norm}.`,
          framework: framework,
        }));
      }
    }
  } catch (err) {
    console.warn(`Database API fetch fallback for ${framework}:`, err);
  }

  if (norm.includes("flask")) return flaskProjects;
  if (norm.includes("streamlit")) return streamlitProjects;
  if (norm.includes("gradio")) return gradioProjects;
  return djangoProjects;
};
