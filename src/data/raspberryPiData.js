/**
 * Fetch projects by technology and year from backend DB API with local dataset fallback.
 */
export const fetchRaspberryPiProjects = async (academicYear = "2020 - 2021") => {
  try {
    const res = await fetch(`${API_BASE}/project_titles.php?tech=raspberry-pi&year=${encodeURIComponent(academicYear)}`);
    if (res.ok) {
      const json = await res.json();
      const items = Array.isArray(json) ? json : json.data || [];
      if (items && items.length > 0) {
        return items.map((item, idx) => ({
          id: item.id || idx + 1,
          title: item.title_name || item.title || `Raspberry Pi Project ${idx + 1}`,
          domain: item.domain || "Raspberry Pi & IoT Systems",
          category: item.category || "IoT & Embedded Systems",
          tech: item.tech ? (Array.isArray(item.tech) ? item.tech : item.tech.split(",")) : ["Raspberry Pi", "Python", "OpenCV", "IoT"],
          description: item.description || "IEEE Standard Raspberry Pi Project implementation with complete Python source code and circuit diagram.",
          abstract: item.abstract || "Comprehensive experimental evaluation and hardware deployment using IEEE standard benchmarks.",
          year: item.academic_year || academicYear,
          difficulty: item.difficulty || "Intermediate",
        }));
      }
    }
  } catch (err) {
    console.warn(`Database API fetch fallback to local data for Raspberry Pi ${academicYear}:`, err);
  }

  if (academicYear.includes("2022")) return raspberryPiProjects2022;
  if (academicYear.includes("2021")) return raspberryPiProjects2021;
  return raspberryPiProjects2020;
};
